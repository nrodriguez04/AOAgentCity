import { DEFAULT_MODEL_PRICING, DIVISIONS } from "@agent-city/core";
import { permissionsFor, type AgentDefinition } from "./define";

const literal = (value: string | null): string => (value === null ? "null" : `'${value.replaceAll("'", "''")}'`);
const num = (value: number | null): string => (value === null ? "null" : String(value));

/** Dollar-quote long text (instructions, context docs) with a tag that cannot clash. */
function dollar(value: string): string {
  let tag = "md";
  while (value.includes(`$${tag}$`)) tag += "_";
  return `$${tag}$${value}$${tag}$`;
}

/**
 * supabase/seed.sql, generated from packages/core (divisions, pricing) and
 * packages/agents (agents, tool grants). Idempotent: re-applying it updates
 * definitions without touching agent state, metrics or edited context docs.
 */
export function seedSql(agents: AgentDefinition[]): string {
  const out: string[] = [
    "-- supabase/seed.sql",
    "-- GENERATED by `pnpm gen:seed` from packages/core and packages/agents. Do not edit by hand.",
    "-- Safe to re-apply: definitions are upserted; agent state, metrics and edited context docs are kept.",
    "",
    "-- Divisions (spec §1) and their city slots (spec §10.3)",
  ];

  for (const d of DIVISIONS) {
    out.push(
      `insert into divisions (id, name, kind, status, summary, context_md, city_slot) values (${literal(d.id)}, ${literal(d.name)}, ${literal(d.kind)}, ${literal(d.status)}, ${literal(d.summary)}, ${dollar(d.contextMd)}, ${literal(JSON.stringify(d.slot))}::jsonb)`,
      "  on conflict (id) do update set name = excluded.name, kind = excluded.kind, status = excluded.status, summary = excluded.summary, city_slot = excluded.city_slot, context_md = coalesce(divisions.context_md, excluded.context_md);",
    );
  }

  out.push("", "-- Agents (spec §6.3) and CrewAI crews (runtime 'crewai')");
  for (const a of agents) {
    out.push(
      `insert into agents (id, division_id, display_name, role, model_tier, runtime, instructions, default_goal, schedule_cron, daily_budget_usd, enabled, state) values (${literal(a.id)}, ${literal(a.division)}, ${literal(a.displayName)}, ${literal(a.role)}, ${literal(a.modelTier)}, ${literal(a.runtime)}, ${dollar(a.instructions)}, ${literal(a.defaultGoal)}, ${literal(a.schedule)}, ${a.dailyBudgetUsd}, ${a.enabled}, '${a.enabled ? "idle" : "disabled"}')`,
      "  on conflict (id) do update set division_id = excluded.division_id, display_name = excluded.display_name, role = excluded.role, model_tier = excluded.model_tier, runtime = excluded.runtime, instructions = excluded.instructions, default_goal = excluded.default_goal, schedule_cron = excluded.schedule_cron, daily_budget_usd = excluded.daily_budget_usd, enabled = excluded.enabled;",
    );
  }

  out.push("", "-- Least-privilege tool grants: each tool at exactly its registered tier (spec §7)");
  out.push(`delete from agent_permissions where agent_id in (${agents.map((a) => literal(a.id)).join(", ")});`);
  for (const a of agents) {
    const rows = permissionsFor(a).map((p) => `  (${literal(a.id)}, ${literal(p.tool_name)}, '${p.max_tier}')`);
    out.push(`insert into agent_permissions (agent_id, tool_name, max_tier) values\n${rows.join(",\n")};`);
  }

  out.push("", "-- Model pricing, USD per million tokens (spec §9)");
  for (const p of DEFAULT_MODEL_PRICING) {
    out.push(
      `insert into model_pricing (model, input_per_mtok, output_per_mtok, cache_write_5m_per_mtok, cache_write_1h_per_mtok, cache_read_per_mtok, long_context_threshold, long_input_per_mtok, long_output_per_mtok) values (${literal(p.model)}, ${p.input_per_mtok}, ${p.output_per_mtok}, ${p.cache_write_5m_per_mtok}, ${p.cache_write_1h_per_mtok}, ${p.cache_read_per_mtok}, ${num(p.long_context_threshold)}, ${num(p.long_input_per_mtok)}, ${num(p.long_output_per_mtok)})`,
      "  on conflict (model) do update set input_per_mtok = excluded.input_per_mtok, output_per_mtok = excluded.output_per_mtok, cache_write_5m_per_mtok = excluded.cache_write_5m_per_mtok, cache_write_1h_per_mtok = excluded.cache_write_1h_per_mtok, cache_read_per_mtok = excluded.cache_read_per_mtok, long_context_threshold = excluded.long_context_threshold, long_input_per_mtok = excluded.long_input_per_mtok, long_output_per_mtok = excluded.long_output_per_mtok, updated_at = now();",
    );
  }
  out.push("");
  return out.join("\n");
}
